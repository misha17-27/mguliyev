<?php
/* Приём заявки.

   Работает двумя путями: со скриптом — fetch и ответ JSON, без скрипта —
   обычная отправка формы и возврат на страницу с ?sent=1. Второй путь важнее,
   чем кажется: заявка не должна теряться из-за того, что у человека
   не выполнился JavaScript.

   Защита от ботов без внешних сервисов и без капчи:
     — поле-ловушка, скрытое от человека: заполнено — значит бот;
     — время заполнения: форма, отправленная быстрее трёх секунд, не человеческая;
     — ограничение частоты по адресу: не чаще одной заявки в минуту.
   Это не останавливает целевой спам, но отсекает основную массу переборщиков. */

/* require_once, а не require: bootstrap.php уже подтягивает turnstile.php,
   а тот — security.php. Повторное подключение того же файла объявило бы
   функции второй раз и уронило бы приём заявки целиком. */
require __DIR__ . '/../app/bootstrap.php';
require_once __DIR__ . '/../app/security.php';
require_once __DIR__ . '/../app/mailer.php';

$cfg  = I18n::$cfg;
$ajax = strtolower($_SERVER['HTTP_X_REQUESTED_WITH'] ?? '') === 'fetch';

/* Куда вернуть посетителя. Значение приходит из формы, то есть снаружи,
   и без проверки это открытый редирект: достаточно подставить чужой адрес,
   чтобы наш домен уводил на него. Принимаем только путь внутри сайта:
   начинается с одного слэша, без схемы, без второго слэша в начале. */
$back = (string)($_POST['back'] ?? '');
if ($back === '' || $back[0] !== '/' || strpos($back, '//') === 0 || strpos($back, "\\") !== false) {
    $back = u('/kontakty/');
}
$back = strtok($back, '?#');

function finish(bool $ok, string $key, string $back, bool $ajax): void
{
    if ($ajax) {
        header('Content-Type: application/json; charset=utf-8');
        echo json_encode(['ok' => $ok, 'message' => t($key)], JSON_UNESCAPED_UNICODE);
        exit;
    }
    $sep = strpos($back, '?') === false ? '?' : '&';
    header('Location: ' . $back . $sep . ($ok ? 'sent=1' : 'error=1') . '#contact', true, 303);
    exit;
}

if (($_SERVER['REQUEST_METHOD'] ?? 'GET') !== 'POST') {
    finish(false, 'form.error', $back, $ajax);
}

/* Ловушка и время заполнения */
if (trim((string)($_POST['website'] ?? '')) !== '') {
    finish(true, 'form.ok', $back, $ajax);          // боту отвечаем «принято» и молчим
}
/* Метка времени обязательна. Раньше её отсутствие проверку просто
   отключало: достаточно было не прислать поле. Теперь нет метки —
   нет и заявки; настоящая форма присылает её всегда.
   Верхняя граница нужна против заранее заготовленных меток. */
$ts  = (int)($_POST['ts'] ?? 0);
$now = time();
if ($ts <= 0 || $now - $ts < 3 || $now - $ts > 86400) {
    finish(false, 'form.spam', $back, $ajax);
}

/* Частота по адресу.

   Адрес берём через client_ip(): сайт стоит за Cloudflare, и REMOTE_ADDR
   здесь — это всегда адрес Cloudflare, один на всех. Ограничение по нему
   либо не работает вовсе, либо запирает сразу всех посетителей.

   Метка лежит в хранилище, а не в общей временной папке сервера: на
   виртуальном хостинге её содержимое видят соседние аккаунты. */
$lock = 'locks/lead-' . ip_key('lead') . '.json';
$prev = Store::read($lock);
if ($prev && $now - (int)($prev['last'] ?? 0) < 60) {
    finish(false, 'form.often', $back, $ajax);
}

/* Общий потолок: не больше 60 заявок в час со всего сайта.

   Ограничение по адресу защищает от одного источника, но не от многих:
   ботнет шлёт с тысяч адресов, и каждая заявка — файл на диске и письмо.
   Настоящих заказчиков у студии не бывает шестьдесят в час, а вот поток
   ботов бывает. Выше потолка заявки не пишутся и письма не уходят —
   а не наоборот, когда кончается место на диске и ломается весь сайт. */
$hour = 'locks/leads-hour.json';
$h = Store::read($hour) ?? [];
$hourStart = (int)($h['from'] ?? 0);
$hourCount = $now - $hourStart < 3600 ? (int)($h['n'] ?? 0) : 0;
if ($hourCount >= 60) {
    error_log('Заявки: потолок 60 в час достигнут, приём приостановлен');
    /* Своё сообщение, а не «заявка уже отправлена»: человек под потолок
       попадает, ничего не отправив, — просто в час, когда форму заливают
       боты. Ему нужен другой путь связаться, а не непонятный отказ. */
    finish(false, 'form.busy', $back, $ajax);
}
Store::write($hour, [
    'from' => $now - $hourStart < 3600 ? $hourStart : $now,
    'n'    => $hourCount + 1,
]);

/* Метку ставим СРАЗУ, а не после отправки письма.

   Раньше она писалась в самом конце, и десять одновременных запросов
   успевали пройти проверку все до единого: каждый читал метку раньше,
   чем её поставил предыдущий. Форма превращалась в рассыльщик и занимала
   все рабочие процессы PHP отправкой писем.

   Плата за это — отказ по частоте, даже если дальше заявка не прошла
   проверку полей. Она того стоит: минута ожидания против рассылки. */
Store::write($lock, ['last' => $now]);
attempts_sweep_due();

$name  = is_string($_POST['name'] ?? null)  ? trim($_POST['name'])  : '';
$phone = is_string($_POST['phone'] ?? null) ? trim($_POST['phone']) : '';
if ($name === '' || $phone === '') {
    finish(false, 'form.required', $back, $ajax);
}

/* Капча — ПОСЛЕ проверки имени и телефона.

   Токен одноразовый: проверив его раньше, мы сожгли бы его и на отказе
   «заполните имя и телефон». Человек дописывает телефон, жмёт отправить
   второй раз — и получает уже отказ капчи, с тем же результатом по кругу.

   Ограничение на обращения к Cloudflare отдельное от ограничения заявок:
   заявка пишется только при успехе, а проверка капчи — это исходящий
   запрос, который бот может вызывать бесконечно. Без счётчика /send.php
   становится усилителем: один запрос к нам — один запрос к Cloudflare.

   Недоступность Cloudflare заявку не отбивает: цена отказа — потерянный
   заказчик, а ловушка, метка времени и ограничение частоты остаются
   на месте. Решённый отказ (success:false) не пропускается никогда. */
if (ts_on()) {
    $capKey  = ip_key('cap');
    $capLock = attempts_get('cap', $capKey);
    if ($capLock['until'] > time()) {
        finish(false, 'form.often', $back, $ajax);
    }
    attempts_fail('cap', $capKey, 20, 600, 600);

    $cap = ts_verify($_POST['cf-turnstile-response'] ?? null, 'lead');
    if (!$cap['ok']) {
        finish(false, ts_message($cap), $back, $ajax);
    }
} else {
    $cap = ['ok' => true, 'skipped' => false, 'note' => ''];
}

/* Через clean_text: она чинит битый UTF-8. Без этого preg_replace с /u
   на битой строке возвращал null, и имя или телефон молча обнулялись —
   уже ПОСЛЕ проверки, что они заполнены. */
$clean = static fn($s, int $max): string =>
    mb_substr(clean_text(strip_tags(is_string($s) ? $s : '')), 0, $max);

$fields = [
    'Имя'      => $clean($name, 120),
    'Телефон'  => $clean($phone, 60),
    'Услуга'   => $clean((string)($_POST['service'] ?? ''), 80),
    'Бюджет'   => $clean((string)($_POST['budget'] ?? ''), 80),
    /* clean_text чинит кодировку: битый UTF-8 ронял json_encode, и заявка
       не записывалась на диск — при отказе почты она терялась целиком. */
    'Задача'   => mb_substr(clean_text(strip_tags(is_string($_POST['message'] ?? null) ? $_POST['message'] : ''), true), 0, 4000),
    'Язык'     => I18n::$lang,
    'Страница' => $clean((string)($_POST['back'] ?? ''), 200),
];

$body = '';
foreach ($fields as $k => $v) {
    if ($v !== '') $body .= $k . ': ' . $v . "\n";
}
/* Адрес в письме — настоящий адрес посетителя, а не адрес Cloudflare:
   иначе во всех заявках стоял бы один и тот же, и толку от него нет. */
$body .= "\n" . date('d.m.Y H:i') . ' · ' . client_ip();

/* Пропуск по недоступности Cloudflare должен быть виден в письме,
   иначе он тихий: владелец не отличит проверенную заявку от непроверенной. */
if (!empty($cap['skipped'])) {
    $body .= "\n\n[Капча не проверена: " . $cap['note'] . ']';
}

/* Отправляем через app/mailer.php: он сам решит, идти через SMTP
   (если ящик настроен в панели) или через встроенную mail(). Заголовки
   и кодирование кириллицы собраны там же — в одном месте на весь сайт. */
$mail = mail_cfg();
$to   = $mail['to'] !== '' ? $mail['to'] : ($cfg['form']['to'] ?? '');

$res = mail_send(
    $to,
    ($cfg['form']['subject'] ?? 'Заявка с сайта') . ': ' . $fields['Имя'],
    $body
    /* Обратного адреса нет: форма собирает имя и телефон, почту не
       спрашивает. Появится поле почты — сюда добавится reply_to,
       и «Ответить» в почтовой программе будет попадать заказчику. */
);
$sent = $res['ok'];

/* Заявка сохраняется ВСЕГДА, а не только когда письмо не ушло.

   Причин две. Первая: письмо может уйти и потеряться по дороге — попасть
   в спам, быть удалённым случайно, не дойти из-за переполненного ящика.
   Вторая: в панели нужен список заявок, иначе единственная их история —
   это чужой почтовый ящик, и посмотреть «что было в прошлом месяце»
   с другого устройства невозможно.

   ЭТО ЛИЧНЫЕ ДАННЫЕ. Имя и телефон живого человека лежат на диске,
   поэтому: папка вне корня сайта (из сети недостижима), доступ только
   из панели по паролю, и в панели есть кнопка удаления — и одной заявки,
   и всех старше выбранного срока. Хранить их вечно не нужно никому. */
$leadFile = 'leads/' . date('Y-m-d-His') . '-' . bin2hex(random_bytes(3)) . '.json';
Store::write($leadFile, [
    'at'      => date('d.m.Y H:i'),
    'ts'      => $now,
    'fields'  => $fields,
    'ip'      => client_ip(),
    'lang'    => I18n::$lang,
    'sent'    => $sent,
    'via'     => $res['via'] ?? '-',
    'error'   => $sent ? '' : $res['error'],
    'captcha' => !empty($cap['skipped']) ? ('не проверена: ' . $cap['note']) : '',
    'new'     => true,
]);

if (!$sent) {
    /* Письмо не ушло — причина должна остаться и в журнале сервера,
       чтобы её было видно и без панели. */
    error_log('Заявка не отправлена: ' . $res['error']);
}

if (random_int(1, 50) === 1) {
    attempts_sweep('lead', 3600);
    attempts_sweep('cap', 3600);
}

finish((bool)$sent, $sent ? 'form.ok' : 'form.error', $back, $ajax);
